const MIME_EXTENSIONS: Record<string, string> = {
  'image/png': 'png',
  'image/jpeg': 'jpg',
  'image/gif': 'gif',
  'image/webp': 'webp',
  'image/avif': 'avif',
  'image/svg+xml': 'svg',
  'image/bmp': 'bmp',
  'image/x-icon': 'ico',
  'font/woff': 'woff',
  'font/woff2': 'woff2',
  'font/ttf': 'ttf',
  'font/otf': 'otf',
  'audio/mpeg': 'mp3',
  'audio/wav': 'wav',
  'audio/ogg': 'ogg',
  'audio/mp4': 'm4a',
  'video/mp4': 'mp4',
  'video/webm': 'webm',
  'application/pdf': 'pdf',
};

function addText(files: ZipEntry[], path: string, text: string): void {
  files.push({path, data: new TextEncoder().encode(text)});
}

function addJson(files: ZipEntry[], path: string, value: unknown): void {
  addText(files, path, JSON.stringify(value, null, 2));
}

function extensionFromUrl(url: string): string {
  try {
    const pathname = new URL(url).pathname;
    const last = pathname.split('/').pop() ?? '';
    const match = last.match(/\.([a-z0-9]{1,8})$/i);
    return match?.[1]?.toLowerCase() ?? '';
  } catch {
    return '';
  }
}

function extensionFromMime(mime: string): string {
  return MIME_EXTENSIONS[mime.split(';')[0]?.trim().toLowerCase() ?? ''] ?? '';
}

function categoryForAsset(mime: string, url: string): string {
  const clean = mime.split(';')[0]?.trim().toLowerCase() ?? '';
  if (clean.startsWith('image/')) {
    return 'images';
  }
  if (clean.startsWith('font/') || /font-(woff|ttf|otf)/.test(clean)) {
    return 'fonts';
  }
  if (clean.startsWith('audio/') || clean.startsWith('video/')) {
    return 'media';
  }
  if (clean === 'application/pdf') {
    return 'documents';
  }
  if (clean && /^(text\/|application\/(json|javascript|xml|xhtml\+xml))/.test(clean)) {
    return '';
  }
  const extension = extensionFromUrl(url);
  if (['png', 'jpg', 'jpeg', 'gif', 'webp', 'avif', 'svg', 'bmp', 'ico'].includes(extension)) {
    return 'images';
  }
  if (['woff', 'woff2', 'ttf', 'otf', 'eot'].includes(extension)) {
    return 'fonts';
  }
  if (['mp3', 'wav', 'ogg', 'm4a', 'mp4', 'webm', 'ogv', 'mov'].includes(extension)) {
    return 'media';
  }
  if (['pdf'].includes(extension)) {
    return 'documents';
  }
  return '';
}

function fnv1a(value: string): string {
  let hash = 0x811c9dc5;
  for (let i = 0; i < value.length; i++) {
    hash ^= value.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(16).padStart(8, '0');
}

function slug(value: string, maxLength = 80): string {
  let result = value.replace(/[<>:"/\\|?*\u0000-\u001f]/g, '_').replace(/\s+/g, ' ').trim().replace(/[. ]+$/g, '');
  if (result.length > maxLength) {
    const dot = result.lastIndexOf('.');
    const extension = dot > 0 && result.length - dot <= 10 ? result.slice(dot) : '';
    result = result.slice(0, maxLength - extension.length) + extension;
  }
  return result || 'file';
}

function hostOf(url: string): string {
  try {
    return slug(new URL(url).hostname || 'unknown', 60);
  } catch {
    return 'unknown';
  }
}

function assetPath(url: string, mime: string, index: number): string {
  const category = categoryForAsset(mime, url) || 'other';
  const extension = extensionFromMime(mime) || extensionFromUrl(url) || 'bin';
  let base = 'file';
  try {
    const parsed = new URL(url);
    base = decodeURIComponent(parsed.pathname.split('/').filter(Boolean).pop() ?? parsed.hostname) || 'file';
  } catch {
    base = 'file';
  }
  base = slug(base, 70);
  if (!base.toLowerCase().endsWith(`.${extension}`)) {
    base = `${base}.${extension}`;
  }
  return `assets/${category}/${hostOf(url)}/${String(index).padStart(4, '0')}-${fnv1a(url)}-${base}`;
}

function cookieMatchesHost(domain: string, host: string): boolean {
  const cleanDomain = domain.replace(/^\./, '').toLowerCase();
  const cleanHost = host.toLowerCase();
  return Boolean(cleanDomain) && (cleanHost === cleanDomain || cleanHost.endsWith(`.${cleanDomain}`));
}

function cookiesToNetscape(cookies: Array<{
  domain: string,
  path: string,
  name: string,
  value: string,
  expires: number,
  httpOnly: boolean,
  secure: boolean,
  session: boolean,
}>): string {
  const lines = [
    '# Netscape HTTP Cookie File',
    '# Generated by DevTools Export Everything.',
    '# domain\tincludeSubdomains\tpath\tsecure\texpiry\tname\tvalue',
    '',
  ];
  for (const cookie of cookies) {
    if (!cookie.domain) {
      continue;
    }
    const domain = cookie.domain.replace(/[\t\r\n]/g, ' ');
    const hostOnly = !domain.startsWith('.');
    const expires = Number(cookie.expires);
    const expiry = Number.isFinite(expires) && expires > 0 ? Math.floor(expires) : 0;
    lines.push([
      `${cookie.httpOnly ? '#HttpOnly_' : ''}${domain}`,
      hostOnly ? 'FALSE' : 'TRUE',
      cookie.path.replace(/[\t\r\n]/g, ''),
      cookie.secure ? 'TRUE' : 'FALSE',
      String(expiry),
      cookie.name.replace(/[\t\r\n]/g, ''),
      cookie.value.replace(/[\t\r\n]/g, ' '),
    ].join('\t'));
  }
  lines.push('');
  return lines.join('\n');
}

function timestamp(): string {
  return new Date().toISOString().replace(/[:.]/g, '-');
}

async function evaluateJson(target: SDK.Target.Target, expression: string): Promise<unknown> {
  try {
    const response = await target.runtimeAgent().invoke_evaluate({
      expression,
      returnByValue: true,
      awaitPromise: true,
    });
    const value = response.result.value;
    if (typeof value !== 'string') {
      return null;
    }
    return JSON.parse(value);
  } catch {
    return null;
  }
}

async function collectStorage(target: SDK.Target.Target): Promise<string|null> {
  const expression = `(async () => {
    const out = {localStorage: {}, sessionStorage: {}, indexedDB: [], caches: [], errors: []};
    const read = (store, destination) => {
      try {
        for (let i = 0; i < store.length; i++) {
          const key = store.key(i);
          if (key !== null) destination[key] = store.getItem(key);
        }
      } catch (error) {
        out.errors.push(String(error));
      }
    };
    read(localStorage, out.localStorage);
    read(sessionStorage, out.sessionStorage);
    try {
      if (window.caches) out.caches = await caches.keys();
    } catch (error) {
      out.errors.push('caches: ' + String(error));
    }
    try {
      if (indexedDB.databases) {
        for (const info of await indexedDB.databases()) {
          if (!info.name) continue;
          const db = await new Promise(resolve => {
            let settled = false;
            const done = value => { if (!settled) { settled = true; resolve(value); } };
            const request = indexedDB.open(info.name);
            request.onsuccess = () => done(request.result);
            request.onerror = () => done(null);
            setTimeout(() => done(null), 4000);
          });
          if (!db) continue;
          const dump = {name: db.name, version: db.version, stores: []};
          for (const storeName of Array.from(db.objectStoreNames)) {
            const rows = [];
            const store = db.transaction(storeName, 'readonly').objectStore(storeName);
            await new Promise(resolve => {
              const cursorRequest = store.openCursor();
              cursorRequest.onsuccess = () => {
                const cursor = cursorRequest.result;
                if (!cursor || rows.length >= 100) { resolve(); return; }
                try {
                  rows.push({key: String(cursor.primaryKey), value: JSON.stringify(cursor.value).slice(0, 100000)});
                } catch (error) {
                  rows.push({key: String(cursor.primaryKey), error: String(error)});
                }
                cursor.continue();
              };
              cursorRequest.onerror = () => resolve();
            });
            dump.stores.push({name: storeName, rows, truncated: rows.length >= 100});
          }
          db.close();
          out.indexedDB.push(dump);
        }
      }
    } catch (error) {
      out.errors.push('indexedDB: ' + String(error));
    }
    return JSON.stringify(out);
  })()`;
  try {
    const response = await target.runtimeAgent().invoke_evaluate({
      expression,
      returnByValue: true,
      awaitPromise: true,
    });
    return typeof response.result.value === 'string' ? response.result.value : null;
  } catch {
    return null;
  }
}

async function collectPageMetadata(target: SDK.Target.Target): Promise<unknown> {
  const expression = `(() => {
    const absolute = value => { try { return new URL(value, location.href).href; } catch { return value; } };
    const images = [];
    for (const image of Array.from(document.images)) {
      const src = image.currentSrc || image.src;
      if (src) images.push({src: absolute(src), alt: image.alt, width: image.naturalWidth, height: image.naturalHeight});
    }
    const backgrounds = new Set();
    for (const element of Array.from(document.querySelectorAll('*'))) {
      const style = getComputedStyle(element);
      for (const property of ['backgroundImage', 'borderImageSource', 'listStyleImage']) {
        const value = style.getPropertyValue(property);
        if (!value || value === 'none' || !value.includes('url(')) continue;
        const regex = /url\\((['"]?)(.*?)\\1\\)/g;
        let match;
        while ((match = regex.exec(value))) {
          if (match[2] && !match[2].startsWith('data:')) backgrounds.add(absolute(match[2]));
        }
      }
    }
    return JSON.stringify({
      url: location.href,
      title: document.title,
      referrer: document.referrer,
      readyState: document.readyState,
      charset: document.characterSet,
      userAgent: navigator.userAgent,
      language: navigator.language,
      viewport: {
        width: innerWidth,
        height: innerHeight,
        devicePixelRatio,
        scrollWidth: document.documentElement.scrollWidth,
        scrollHeight: document.documentElement.scrollHeight,
      },
      counts: {
        elements: document.querySelectorAll('*').length,
        images: document.images.length,
        links: document.links.length,
        scripts: document.scripts.length,
        forms: document.forms.length,
        iframes: document.querySelectorAll('iframe').length,
      },
      images,
      backgroundUrls: Array.from(backgrounds),
    });
  })()`;
  return await evaluateJson(target, expression);
}

function readmeText(): string {
  return [
    'EXPORT EVERYTHING — complete DevTools capture',
    '',
    'har/page.har                 HAR with response bodies and headers.',
    'cookies/cookies.json         Cookie objects (HttpOnly included).',
    'cookies/cookies.j2team.json  J2TEAM Cookies-compatible JSON.',
    'cookies/cookies.txt          Netscape cookies.txt (curl/J2TEAM).',
    'page/dom.html                Live DOM at export time.',
    'page/page.json               Metadata, images and backgrounds.',
    'page/page.mhtml              MHTML snapshot.',
    'page/screenshot.png          Viewport screenshot.',
    'page/screenshot-full.png     Full-page screenshot.',
    'console/console.jsonl       Console entries, one JSON object per line.',
    'console/console.txt         Human-readable console log.',
    'storage/storage.json         localStorage, sessionStorage, IndexedDB, caches.',
    'assets/...                   Images, fonts, media and PDFs from response bodies.',
    'manifest.json                Counts, warnings and file list.',
    '',
    'Cookies and the HAR contain authentication material. Keep this archive secret.',
    '',
  ].join('\n');
}

/**
 * Collects HAR, cookies, DOM, console, storage, screenshots and assets for the
 * inspected page and saves a ZIP next to the normal DevTools downloads.
 */
export async function exportEverything(requests: SDK.NetworkRequest.NetworkRequest[]): Promise<void> {
  const target = SDK.TargetManager.TargetManager.instance().scopeTarget();
  if (!target) {
    Common.Console.Console.instance().error('Export Everything: no inspected target.');
    return;
  }

  const files: ZipEntry[] = [];
  const warnings: string[] = [];
  const usedPaths = new Set<string>();
  const pageUrl = target.inspectedURL();
  let host = 'page';
  try {
    host = new URL(pageUrl).hostname || 'page';
  } catch {
    host = 'page';
  }

  try {
    const progress = new Common.Progress.Progress();
    const composite = new Common.Progress.CompositeProgress(progress);
    const har = await HAR.Writer.harStringForRequests(requests.slice(), {sanitize: false}, composite);
    addText(files, 'har/page.har', har);

    try {
      const {cookies} = await target.networkAgent().invoke_getAllCookies();
      const filtered = cookies.filter(cookie => cookieMatchesHost(cookie.domain, host));
      addJson(files, 'cookies/cookies.json', filtered);
      addJson(files, 'cookies/cookies.j2team.json', filtered.map(cookie => ({
        domain: cookie.domain,
        expirationDate: cookie.expires > 0 ? cookie.expires : undefined,
        hostOnly: !cookie.domain.startsWith('.'),
        httpOnly: cookie.httpOnly,
        name: cookie.name,
        path: cookie.path,
        sameSite: String(cookie.sameSite ?? 'unspecified').toLowerCase(),
        secure: cookie.secure,
        session: cookie.session,
        storeId: '0',
        value: cookie.value,
        ...(cookie.partitionKey ? {partitionKey: cookie.partitionKey} : {}),
      })));
      addText(files, 'cookies/cookies.txt', cookiesToNetscape(filtered));
    } catch (error) {
      warnings.push(`cookies: ${error instanceof Error ? error.message : String(error)}`);
    }

    const domModel = target.model(SDK.DOMModel.DOMModel);
    const document = await domModel?.requestDocument();
    const dom = document ? await document.getOuterHTML(true) : null;
    if (dom) {
      addText(files, 'page/dom.html', dom);
    } else {
      warnings.push('DOM snapshot unavailable');
    }

    const metadata = await collectPageMetadata(target);
    if (metadata) {
      addJson(files, 'page/page.json', metadata);
    }

    try {
      const snapshot = await target.pageAgent().invoke_captureSnapshot({format: 'mhtml'});
      addText(files, 'page/page.mhtml', snapshot.data);
    } catch (error) {
      warnings.push(`MHTML: ${error instanceof Error ? error.message : String(error)}`);
    }

    const screenModel = target.model(SDK.ScreenCaptureModel.ScreenCaptureModel);
    if (screenModel) {
      try {
        const viewport = await screenModel.captureScreenshot(
            'png', 100, SDK.ScreenCaptureModel.ScreenshotMode.FROM_VIEWPORT);
        if (viewport) {
          files.push({path: 'page/screenshot.png', data: Common.Base64.decode(viewport)});
        }
        const full = await screenModel.captureScreenshot(
            'png', 100, SDK.ScreenCaptureModel.ScreenshotMode.FULLPAGE);
        if (full) {
          files.push({path: 'page/screenshot-full.png', data: Common.Base64.decode(full)});
        }
      } catch (error) {
        warnings.push(`screenshots: ${error instanceof Error ? error.message : String(error)}`);
      }
    } else {
      warnings.push('screen capture is not available for this target');
    }

    const messages = SDK.ConsoleModel.ConsoleModel.allMessagesUnordered(SDK.TargetManager.TargetManager.instance());
    const consoleRows = messages.map(message => ({
      level: String(message.level ?? message.type),
      text: message.messageText,
      url: message.url ?? '',
      line: message.line,
      timestamp: message.timestamp,
      stack: message.stackTrace ? JSON.stringify(message.stackTrace) : '',
    }));
    addText(files, 'console/console.jsonl',
            consoleRows.map(row => JSON.stringify(row)).join('\n') + (consoleRows.length ? '\n' : ''));
    addText(files, 'console/console.txt', consoleRows.map(row => {
      const stack = row.stack ? `\n${row.stack}` : '';
      return `[${new Date(row.timestamp).toISOString()}] ${row.level.toUpperCase()} ${row.url}\n${row.text}${stack}`;
    }).join('\n\n'));

    const storage = await collectStorage(target);
    if (storage) {
      addText(files, 'storage/storage.json', storage);
    } else {
      warnings.push('storage snapshot unavailable');
    }

    let assetIndex = 0;
    const seenAssets = new Set<string>();
    for (const request of requests) {
      try {
        const content = await request.requestContentDataIfAvailable();
        if (TextUtils.ContentData.ContentData.isError(content)) {
          continue;
        }
        const category = categoryForAsset(content.mimeType, request.url());
        if (!category || seenAssets.has(request.url())) {
          continue;
        }
        seenAssets.add(request.url());
        const bytes = content.createdFromBase64 ? Common.Base64.decode(content.base64) :
                                                   new TextEncoder().encode(content.text);
        let path = assetPath(request.url(), content.mimeType, assetIndex);
        while (usedPaths.has(path)) {
          path = path.replace(/\.([^.]+)$/, '-2.$1');
        }
        usedPaths.add(path);
        files.push({path, data: bytes});
        assetIndex++;
      } catch (error) {
        warnings.push(`asset ${request.url()}: ${error instanceof Error ? error.message : String(error)}`);
      }
    }

    addText(files, 'README.txt', readmeText());

    const manifest = {
      tool: 'DevTools Export Everything',
      version: '1.0.0',
      exportedAt: new Date().toISOString(),
      page: {url: pageUrl, title: ''},
      counts: {
        harEntries: requests.length,
        cookies: files.filter(file => file.path.startsWith('cookies/')).length,
        consoleEntries: consoleRows.length,
        assets: assetIndex,
        files: files.length + 1,
      },
      warnings,
      files: files.map(file => ({path: file.path, size: file.data.length})),
    };
    addJson(files, 'manifest.json', manifest);

    const zip = createZip(files);
    const base64 = await Common.Base64.encode(zip);
    const filename = `${slug(host)}-export-${timestamp()}.zip` as Platform.DevToolsPath.RawPathString;
    const fileManager = Workspace.FileManager.FileManager.instance();
    const saved = await fileManager.save(
        filename, new TextUtils.ContentData.ContentData(base64, true, 'application/zip'), true);
    fileManager.close(filename);
    if (saved) {
      Common.Console.Console.instance().log(
          `Export Everything: ${files.length} files written to ${filename}.`);
    } else {
      Common.Console.Console.instance().warn('Export Everything: save was cancelled.');
    }
    if (warnings.length) {
      Common.Console.Console.instance().warn(`Export Everything: ${warnings.length} warning(s). ${warnings.join(' | ')}`);
    }
  } catch (error) {
    Common.Console.Console.instance().error(
        `Export Everything failed: ${error instanceof Error ? error.message : String(error)}`);
  }
}
